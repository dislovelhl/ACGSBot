#!/usr/bin/env node
// Re-runnable ACGSBot rebrand of user-visible OpenMausBot names. Usage: node scripts/rebrand-acgs.mjs [--write]
// Internal identifiers, env vars, the data directory, wire headers, CLI verbs and upstream service hosts are kept so
// upstream merges stay possible. License, notice, copyright and third-party files are never changed (Apache-2.0 §4).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const write = process.argv.includes("--write");

const SKIP_PATHS = [
  /^LICENSE$/, /^NOTICE$/, /^LICENSING\.md$/, /^CLA\.md$/, /(^|\/)LICENSE[^/]*$/, /^third_party\//, /^enterprise\//,
  /pnpm-lock\.yaml$/, /^scripts\/rebrand-acgs\.mjs$/, /^\.tmpexp\//,
  // Pinned by checksums or generated byte-for-byte: package fixtures, E2E wire vectors, versioned judge prompts.
  /^shared\/package-fixtures\/(?!manifest\.json$)/, /^companion\/src\/e2e\/(vectors\/|gen-vectors\.ts$)/, /^evals\/live\/judge\/prompts\//,
  /^src\/lib\/github-refs\.test\.ts$/, /^src\/components\/TaskPicker\.test\.ts$/,
];
const TEXT_EXT = /\.(ts|tsx|mts|cts|js|mjs|cjs|json|jsonc|md|mdx|yml|yaml|html|css|txt|sh|ps1|toml|xml|svg|plist|webmanifest|desktop|apparmor|example|conf|service|nsh|iss)$|^[^.]+$|^\.gitignore$/i;
// Attribution, and lines naming the upstream people who receive data, keep upstream's words.
const KEEP_LINE = /copyright|\(c\)|©|trademark|modified version of|affiliated|\bmodified\b|changed for/i;
// Protocol constants shared with the upstream phone apps: renaming them breaks the HPKE handshake.
// FAILED_MARKER detects a relayed failure line, which names the upstream MausBot team in every language.
const KEEP_PROTOCOL = /\bPHONE_SECRET_INFO\b|\bFAILED_MARKER\b|failure line names MausBot/;
const KEEP_PEOPLE = /\bMilind\b[^\n]*\bOmkar\b|\bOmkar\b[^\n]*\bMilind\b/;
// Upstream's hosted services and team keep their names: ACGS does not run them.
const TEAM = "(?:team|équipe|equipe|equipo|squadra|zespo[łl]\\p{L}*|команд\\p{L}*|팀|チーム|团队|團隊|टीम|ekib\\p{L}*|nhóm|tým\\p{L}*)";
const PROTECTED = new RegExp([
  "\\b(?:Open)?MausBot (?:Cloud|Pro|Relay)\\b",
  `${TEAM}\\s+(?:(?:do|da|de|del|di|della|du|von|of)\\s+)?(?:Open)?MausBot`,
  `(?:Open)?MausBot[-\\s]?${TEAM}(?!mate)`,
].join("|"), "giu");

const RULES = [
  { name: "upstream-repo", re: /milind-soni(\\?)\/OpenMausBot/g, to: "dislovelhl$1/ACGSBot" },
  { name: "app-id", re: /\bcom\.openmausbot\.app\b/g, to: "ai.acgs.acgsbot" },
  { name: "product", re: /(?<!X-)(?<!upstream )(?<!(?<!app)\.)(?:(?<=\\[nrt]|%0[ADad])|\b)OpenMausBot\b(?!:\/\/)/g, to: "ACGSBot" },
  { name: "helper-bot", re: /(?<!(?<!app)\.)(?:(?<=\\[nrt]|%0[ADad])|\b)MausBot\b(?!:\/\/)/g, to: "ACGS" },
];
const ARTICLE = /\b([aA]) (ACGS)/g;

function rebrandLine(line, english) {
  const held = [];
  let next = line.replace(PROTECTED, (phrase) => { held.push(phrase); return `\uE000${held.length - 1}\uE000`; });
  for (const rule of RULES) {
    next = next.replace(rule.re, (...match) => {
      counts[rule.name]++;
      return rule.to.replace("$1", typeof match[1] === "string" ? match[1] : "");
    });
  }
  if (english) next = next.replace(ARTICLE, (_, a, name) => `${a}n ${name}`);
  return next.replace(/\uE000(\d+)\uE000/g, (_, i) => held[Number(i)]);
}

const files = execFileSync("git", ["ls-files", "-z"], { encoding: "utf8" }).split("\0").filter(Boolean);
const counts = Object.fromEntries(RULES.map((rule) => [rule.name, 0]));
let changedFiles = 0;

for (const file of files) {
  if (SKIP_PATHS.some((re) => re.test(file)) || !TEXT_EXT.test(file.split("/").pop())) continue;
  let text;
  try { text = readFileSync(file, "utf8"); } catch { continue; }
  if (text.includes("\0")) continue;
  const english = !/(^|\/)locales?\//.test(file) || /(^|\/)en[^/]*\.json$/.test(file);
  let fileChanged = false;
  const out = text.split("\n").map((line) => {
    if (KEEP_LINE.test(line) || KEEP_PEOPLE.test(line) || KEEP_PROTOCOL.test(line)) return line;
    const next = rebrandLine(line, english);
    if (next !== line) fileChanged = true;
    return next;
  }).join("\n");
  if (fileChanged) {
    changedFiles++;
    if (write) writeFileSync(file, out);
  }
}

console.log(JSON.stringify({ mode: write ? "write" : "dry-run", changedFiles, replacements: counts }));
